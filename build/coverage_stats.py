"""Print codepoint coverage of the merged font by block group (for the README)."""
import sys
from fontTools.ttLib import TTFont
GROUPS = [
    ('基本拉丁 / 拉丁扩展 / IPA / 组合符号', [(0x0000, 0x036F), (0x1D00, 0x1DFF), (0x1E00, 0x1EFF), (0x2C60, 0x2C7F), (0xA720, 0xA7FF), (0xAB30, 0xAB6F)]),
    ('希腊文', [(0x0370, 0x03FF), (0x1F00, 0x1FFF)]),
    ('西里尔文', [(0x0400, 0x052F), (0x1C80, 0x1C8F), (0x2DE0, 0x2DFF), (0xA640, 0xA69F)]),
    ('阿拉伯文（含表现形式）', [(0x0600, 0x06FF), (0x0750, 0x077F), (0x0870, 0x08FF), (0xFB50, 0xFDFF), (0xFE70, 0xFEFF)]),
    ('天城文', [(0x0900, 0x097F), (0xA8E0, 0xA8FF)]),
    ('古尔穆基文', [(0x0A00, 0x0A7F)]),
    ('古吉拉特文', [(0x0A80, 0x0AFF)]),
    ('泰文', [(0x0E00, 0x0E7F)]),
    ('老挝文', [(0x0E80, 0x0EFF)]),
    ('藏文', [(0x0F00, 0x0FFF)]),
    ('缅甸文', [(0x1000, 0x109F), (0xA9E0, 0xA9FF), (0xAA60, 0xAA7F)]),
    ('高棉文', [(0x1780, 0x17FF), (0x19E0, 0x19FF)]),
    ('爪哇文', [(0xA980, 0xA9DF)]),
    ('标点 / 符号 / 箭头 / 数学 / 几何等', [(0x2000, 0x2BFF), (0x1F000, 0x1FAFF)]),
    ('CJK 符号与标点 / 假名 / 注音 / 笔画等', [(0x2E80, 0x2FFF), (0x3000, 0x33FF), (0xFE10, 0xFE1F), (0xFE30, 0xFE4F), (0xFF00, 0xFFEF), (0x31C0, 0x31EF)]),
    ('CJK 统一汉字（基本区）', [(0x4E00, 0x9FFF)]),
    ('CJK 扩展 A', [(0x3400, 0x4DBF)]),
    ('CJK 扩展 B', [(0x20000, 0x2A6DF)]),
    ('CJK 扩展 C–I', [(0x2A700, 0x2EE5F), (0x30000, 0x323AF)]),
    ('CJK 兼容汉字', [(0xF900, 0xFAFF), (0x2F800, 0x2FA1F)]),
    ('私用区（含 SF Symbols 等）', [(0xE000, 0xF8FF), (0xF0000, 0x10FFFF)]),
]
f = TTFont(sys.argv[1], lazy=True)
cps = set(f.getBestCmap())
done = set()
for name, rs in GROUPS:
    s = {c for c in cps if any(a <= c <= b for a, b in rs)}
    done |= s
    print('| %s | %d |' % (name, len(s)))
print('| 其他 | %d |' % len(cps - done))
print('| **总计码位** | **%d** |' % len(cps))
print('glyphs', f['maxp'].numGlyphs)
